def maximum_exposure(
    exposure_count: np.ndarray,
    *,
    analysable_mask: np.ndarray | None = None,
) -> int:
    """Return maximum exposure among analysable cells."""

    exposure = _validate_exposure_count(
        exposure_count,
        copy=False,
    )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    if not np.any(
        valid
    ):
        return 0

    return int(
        np.max(
            exposure[
                valid
            ]
        )
    )


def total_exposure(
    exposure_count: np.ndarray,
    *,
    analysable_mask: np.ndarray | None = None,
) -> int:
    """Return total viewpoint-cell visibility relationships."""

    exposure = _validate_exposure_count(
        exposure_count,
        copy=False,
    )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    return int(
        np.sum(
            exposure[
                valid
            ],
            dtype=np.uint64,
        )
    )


# ---------------------------------------------------------------------------
# Validation helpers
# ---------------------------------------------------------------------------


def _validate_exposure_count(
    exposure_count: np.ndarray,
    *,
    copy: bool,
    name: str = "exposure_count",
) -> np.ndarray:
    """Validate a non-negative integer exposure raster."""

    if not isinstance(
        exposure_count,
        np.ndarray,
    ):
        raise TypeError(
            f"{name} must be a numpy.ndarray."
        )

    if exposure_count.ndim != 2:
        raise ValueError(
            f"{name} must be two-dimensional."
        )

    if not np.issubdtype(
        exposure_count.dtype,
        np.integer,
    ):
        raise TypeError(
            f"{name} must use an integer dtype."
        )

    if np.any(
        exposure_count < 0
    ):
        raise ValueError(
            f"{name} cannot contain negative values."
        )

    if copy:
        return exposure_count.copy()

    return exposure_count


def _prepare_analysable_mask(
    analysable_mask: np.ndarray | None,
    *,
    shape: tuple[int, int],
) -> np.ndarray:
    """Return a validated analysable-space mask."""

    if analysable_mask is None:
        return np.ones(
            shape,
            dtype=bool,
        )

    valid = _as_boolean_mask(
        "analysable_mask",
        analysable_mask,
    )

    if valid.shape != shape:
        raise ValueError(
            "analysable_mask does not match the "
            "exposure raster shape."
        )

    return valid


def _as_boolean_mask(
    name: str,
    mask: np.ndarray,
) -> np.ndarray:
    """Validate a two-dimensional mask and return boolean form."""

    if not isinstance(
        mask,
        np.ndarray,
    ):
        raise TypeError(
            f"{name} must be a numpy.ndarray."
        )

    if mask.ndim != 2:
        raise ValueError(
            f"{name} must be two-dimensional."
        )

    return mask.astype(
        bool,
        copy=False,
    )


def _validate_exposure_dtype(
    dtype: np.dtype | type,
) -> np.dtype:
    """Validate the dtype used for cumulative exposure."""

    result = np.dtype(
        dtype
    )

    if not np.issubdtype(
        result,
        np.unsignedinteger,
    ):
        raise TypeError(
            "Exposure dtype must be an unsigned integer dtype."
        )

    return result


def _increment_exposure(
    exposure_count: np.ndarray,
    contribution_mask: np.ndarray,
) -> None:
    """Increment exposure while preventing integer overflow."""

    if not np.any(
        contribution_mask
    ):
        return

    maximum = np.iinfo(
        exposure_count.dtype
    ).max

    if np.any(
        exposure_count[
            contribution_mask
        ] >= maximum
    ):
        raise OverflowError(
            "Exposure-count dtype cannot represent "
            "another contribution."
        )

    exposure_count[
        contribution_mask
    ] += 1