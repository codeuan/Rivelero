"""Exposure calculations for Rivelero.

This module contains reusable mathematical operations for deriving and
updating spatial exposure products from visibility masks.

Exposure describes the spatial distribution of visual observation
opportunity generated by a collection of Viewpoints or ObservationEvents.

The functions in this module operate only on NumPy arrays. They do not
manage SurveyObservabilityField state, visibility storage, viewpoint
metadata, or viewshed calculation.
"""

from __future__ import annotations

from collections.abc import Iterable

import numpy as np


# ---------------------------------------------------------------------------
# Exposure-count construction
# ---------------------------------------------------------------------------


def exposure_count_from_masks(
    visibility_masks: Iterable[np.ndarray],
    *,
    analysable_mask: np.ndarray | None = None,
    dtype: np.dtype | type = np.uint32,
) -> np.ndarray:
    """Calculate cumulative exposure from multiple visibility masks.

    Parameters
    ----------
    visibility_masks
        Iterable of two-dimensional boolean or binary visibility masks.
        Each mask represents one Viewpoint or ObservationEvent.

    analysable_mask
        Optional boolean mask defining cells that legitimately participate
        in the analysis. Cells outside this mask receive zero exposure.

    dtype
        Unsigned integer dtype used for the exposure-count raster.

    Returns
    -------
    numpy.ndarray
        Integer raster containing the number of supplied visibility masks
        from which each cell is visible.

    Notes
    -----
    Large Rivelero analyses should normally update a
    SurveyObservabilityField incrementally rather than loading every
    visibility mask into RAM simultaneously.
    """

    dtype = _validate_exposure_dtype(
        dtype
    )

    iterator = iter(
        visibility_masks
    )

    try:
        first = next(
            iterator
        )
    except StopIteration as exc:
        raise ValueError(
            "visibility_masks must contain at least one mask."
        ) from exc

    first_mask = _as_boolean_mask(
        "visibility_mask",
        first,
    )

    shape = first_mask.shape

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=shape,
    )

    exposure = np.zeros(
        shape,
        dtype=dtype,
    )

    _increment_exposure(
        exposure,
        first_mask & valid,
    )

    for mask in iterator:

        current = _as_boolean_mask(
            "visibility_mask",
            mask,
        )

        if current.shape != shape:
            raise ValueError(
                "All visibility masks must have the same shape."
            )

        _increment_exposure(
            exposure,
            current & valid,
        )

    exposure[
        ~valid
    ] = 0

    return exposure


