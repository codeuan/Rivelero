def normalize_exposure_global(
    exposure_count: np.ndarray,
    n_sampling_units: int,
    *,
    analysable_mask: np.ndarray | None = None,
    dtype: np.dtype | type = np.float32,
) -> np.ndarray:
    """Normalize exposure by the total number of sampling units.

    The calculation is:

        normalized_exposure(x)
            = exposure_count(x) / n_sampling_units

    This is the initial global Rivelero normalization. It should not be
    confused with future eligibility-aware normalization.
    """

    exposure = _validate_exposure_count(
        exposure_count,
        copy=False,
    )

    if not isinstance(
        n_sampling_units,
        int,
    ):
        raise TypeError(
            "n_sampling_units must be an integer."
        )

    if n_sampling_units < 0:
        raise ValueError(
            "n_sampling_units must be greater than or equal to zero."
        )

    output_dtype = np.dtype(
        dtype
    )

    if not np.issubdtype(
        output_dtype,
        np.floating,
    ):
        raise TypeError(
            "Normalized exposure dtype must be floating point."
        )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    result = np.zeros(
        exposure.shape,
        dtype=output_dtype,
    )

    if n_sampling_units == 0:

        if np.any(
            exposure > 0
        ):
            raise ValueError(
                "Exposure is non-zero but n_sampling_units is zero."
            )

        return result

    if np.any(
        exposure > n_sampling_units
    ):
        raise ValueError(
            "exposure_count cannot exceed n_sampling_units "
            "when using global normalization."
        )

    np.divide(
        exposure,
        float(
            n_sampling_units
        ),
        out=result,
        where=valid,
    )

    result[
        ~valid
    ] = 0.0

    return result


def normalize_exposure_by_eligibility(
    exposure_count: np.ndarray,
    eligible_count: np.ndarray,
    *,
    analysable_mask: np.ndarray | None = None,
    dtype: np.dtype | type = np.float32,
) -> np.ndarray:
    """Normalize exposure by cell-specific observation opportunity.

    Parameters
    ----------
    exposure_count
        Number of sampling units that actually contribute visibility
        to each cell.

    eligible_count
        Number of sampling units considered eligible to observe each
        cell under an externally defined eligibility rule.

    analysable_mask
        Optional boolean mask defining analysable cells.

    dtype
        Floating-point dtype of the result.

    Notes
    -----
    This function provides the mathematical operation required for future
    eligibility-aware exposure normalization.

    It deliberately does not define what makes a Viewpoint eligible to
    observe a cell.
    """

    exposure = _validate_exposure_count(
        exposure_count,
        copy=False,
    )

    eligible = _validate_exposure_count(
        eligible_count,
        copy=False,
        name="eligible_count",
    )

    if (
        exposure.shape
        != eligible.shape
    ):
        raise ValueError(
            "exposure_count and eligible_count must have "
            "the same shape."
        )

    if np.any(
        exposure > eligible
    ):
        raise ValueError(
            "exposure_count cannot exceed eligible_count."
        )

    output_dtype = np.dtype(
        dtype
    )

    if not np.issubdtype(
        output_dtype,
        np.floating,
    ):
        raise TypeError(
            "Normalized exposure dtype must be floating point."
        )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    denominator_valid = (
        valid
        & (eligible > 0)
    )

    result = np.zeros(
        exposure.shape,
        dtype=output_dtype,
    )

    np.divide(
        exposure,
        eligible,
        out=result,
        where=denominator_valid,
    )

    result[
        ~valid
    ] = 0.0

    return result


# ---------------------------------------------------------------------------
# Observation-opportunity support
# ---------------------------------------------------------------------------


def opportunity_count_from_masks(
    opportunity_masks: Iterable[np.ndarray],
    *,
    analysable_mask: np.ndarray | None = None,
    dtype: np.dtype | type = np.uint32,
) -> np.ndarray:
    """Count cell-specific observation opportunities.

    This is mathematically identical to cumulative exposure, but its
    semantic meaning differs.

    Each supplied mask represents whether a sampling unit was eligible
    to observe a cell rather than whether the cell was actually visible.
    """

    return exposure_count_from_masks(
        opportunity_masks,
        analysable_mask=analysable_mask,
        dtype=dtype,
    )


