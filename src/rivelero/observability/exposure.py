def add_visibility_to_exposure(
    exposure_count: np.ndarray,
    visibility_mask: np.ndarray,
    *,
    analysable_mask: np.ndarray | None = None,
    inplace: bool = False,
) -> np.ndarray:
    """Add one visibility contribution to an exposure-count raster.

    Parameters
    ----------
    exposure_count
        Existing non-negative integer exposure raster.

    visibility_mask
        Visibility mask to add.

    analysable_mask
        Optional mask restricting which cells may receive exposure.

    inplace
        If True, modify exposure_count directly. Otherwise return an
        independent updated copy.

    Returns
    -------
    numpy.ndarray
        Updated exposure-count raster.
    """

    exposure = _validate_exposure_count(
        exposure_count,
        copy=not inplace,
    )

    visibility = _as_boolean_mask(
        "visibility_mask",
        visibility_mask,
    )

    if (
        visibility.shape
        != exposure.shape
    ):
        raise ValueError(
            "visibility_mask and exposure_count must have "
            "the same shape."
        )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    contribution = (
        visibility
        & valid
    )

    _increment_exposure(
        exposure,
        contribution,
    )

    exposure[
        ~valid
    ] = 0

    return exposure


def remove_visibility_from_exposure(
    exposure_count: np.ndarray,
    visibility_mask: np.ndarray,
    *,
    analysable_mask: np.ndarray | None = None,
    inplace: bool = False,
) -> np.ndarray:
    """Remove one visibility contribution from an exposure-count raster.

    Parameters
    ----------
    exposure_count
        Existing non-negative integer exposure raster.

    visibility_mask
        Visibility mask whose contribution should be removed.

    analysable_mask
        Optional mask restricting the analysis.

    inplace
        If True, modify exposure_count directly.

    Returns
    -------
    numpy.ndarray
        Updated exposure-count raster.

    Raises
    ------
    ValueError
        If removal would produce negative exposure.
    """

    exposure = _validate_exposure_count(
        exposure_count,
        copy=not inplace,
    )

    visibility = _as_boolean_mask(
        "visibility_mask",
        visibility_mask,
    )

    if (
        visibility.shape
        != exposure.shape
    ):
        raise ValueError(
            "visibility_mask and exposure_count must have "
            "the same shape."
        )

    valid = _prepare_analysable_mask(
        analysable_mask,
        shape=exposure.shape,
    )

    contribution = (
        visibility
        & valid
    )

    if np.any(
        exposure[
            contribution
        ] == 0
    ):
        raise ValueError(
            "Cannot remove visibility contribution because "
            "one or more affected cells currently have zero exposure."
        )

    exposure[
        contribution
    ] -= 1

    exposure[
        ~valid
    ] = 0

    return exposure


